/// 必须与后端生成的 `protocol.Version` 相同。
String protocolVersionFor(Map<String, Object?> idl) {
  final canonical = StringBuffer();
  _writeCanonical(canonical, idl, '');
  final digest = sha256.convert(utf8.encode(canonical.toString()));
  return digest.toString().substring(0, 16);
}

String generateProtocol(Map<String, Object?> idl) => _Generator(idl).protocol();

String generateHttp(Map<String, Object?> idl) => _Generator(idl).http();

// 复现后端 protocolVersion 的编码：Go 以 UseNumber 解码 IDL，再用
// SetEscapeHTML(false) 的 json.Encoder 编码；map 的键按码点排序，与 Go 的
// UTF-8 字节序相同。
void _writeCanonical(StringBuffer out, Object? value, String where) {
  switch (value) {
    case null || bool() || int():
      out.write(value);
    case String():
      _writeGoString(out, value);
    case List<Object?>():
      out.write('[');
      for (var index = 0; index < value.length; index++) {
        if (index > 0) out.write(',');
        _writeCanonical(out, value[index], '$where[$index]');
      }
      out.write(']');
    case Map<String, Object?>():
      final keys = value.keys.toList()..sort(_compareCodePoints);
      out.write('{');
      for (var index = 0; index < keys.length; index++) {
        if (index > 0) out.write(',');
        _writeGoString(out, keys[index]);
        out.write(':');
        _writeCanonical(out, value[keys[index]], _at(where, keys[index]));
      }
      out.write('}');
    default:
      // Go 对数字的原始写法求哈希，解码为 double 后原始写法已丢失，只能重现
      // 整数。
      throw FormatException(
        '${_where(where)}: only integer numbers are supported, found $value',
      );
  }
}

void _writeGoString(StringBuffer out, String value) {
  out.write('"');
  for (final rune in value.runes) {
    switch (rune) {
      case 0x22:
        out.write(r'\"');
      case 0x5c:
        out.write(r'\\');
      case 0x08:
        out.write(r'\b');
      case 0x0c:
        out.write(r'\f');
      case 0x0a:
        out.write(r'\n');
      case 0x0d:
        out.write(r'\r');
      case 0x09:
        out.write(r'\t');
      case < 0x20 || 0x2028 || 0x2029:
        out.write('\\u${rune.toRadixString(16).padLeft(4, '0')}');
      default:
        out.writeCharCode(rune);
    }
  }
  out.write('"');
}

int _compareCodePoints(String left, String right) {
  final a = left.runes.iterator;
  final b = right.runes.iterator;
  while (true) {
    final hasA = a.moveNext();
    final hasB = b.moveNext();
    if (!hasA || !hasB) return (hasA ? 1 : 0) - (hasB ? 1 : 0);
    if (a.current != b.current) return a.current - b.current;
  }
}

