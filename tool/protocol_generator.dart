String _pascal(String value, String where) {
  final lower = _lowerCamel(value, where);
  return lower[0].toUpperCase() + lower.substring(1);
}

String _lowerCamel(String value, String where) {
  final parts = value
      .split(RegExp(r'[^A-Za-z0-9]+'))
      .where((part) => part.isNotEmpty)
      .toList();
  if (parts.isEmpty) {
    throw FormatException('$where: cannot derive a Dart name from "$value"');
  }
  String lowerIfAllCaps(String part) =>
      part == part.toUpperCase() ? part.toLowerCase() : part;
  final first = lowerIfAllCaps(parts.first);
  final buffer = StringBuffer(first[0].toLowerCase() + first.substring(1));
  for (final part in parts.skip(1)) {
    final normalized = lowerIfAllCaps(part);
    buffer.write(normalized[0].toUpperCase() + normalized.substring(1));
  }
  final result = buffer.toString();
  return RegExp(r'^[0-9]').hasMatch(result) ? 'value$result' : result;
}

String _quote(String value) {
  final escaped = value
      .replaceAll(r'\', r'\\')
      .replaceAll("'", r"\'")
      .replaceAll(r'$', r'\$')
      .replaceAll('\n', r'\n')
      .replaceAll('\r', r'\r')
      .replaceAll('\t', r'\t');
  return "'$escaped'";
}

final class ProtocolSourceException implements Exception {
  ProtocolSourceException(this.message);

  final String message;

  @override
  String toString() => message;
}

final class ProtocolLock {
  const ProtocolLock({required this.url, required this.digest});

  final Uri url;

  /// 64 位小写十六进制，不含 `sha256:` 前缀。
  final String digest;
}

typedef IdlDownloader = Future<List<int>> Function(Uri uri);

const _maxIdlBytes = 1024 * 1024;
const _maxRedirects = 5;
const _connectionTimeout = Duration(seconds: 10);
const _downloadTimeout = Duration(seconds: 30);

final _lockDigest = RegExp(r'^sha256:([0-9a-f]{64})$');

// 错误信息不带查询串：重定向到对象存储的地址含签名。
String _describe(Uri uri) => '${uri.scheme}://${uri.host}${uri.path}';

bool _isPlainHttps(Uri uri) =>
    uri.scheme == 'https' && uri.host.isNotEmpty && uri.userInfo.isEmpty;

void _requireHttps(Uri uri) {
  if (!_isPlainHttps(uri)) {
    throw ProtocolSourceException(
      'Only https addresses without credentials are allowed, '
      'got ${_describe(uri)}',
    );
  }
}

ProtocolLock parseProtocolLock(String text) {
  if (text.contains('\r')) {
    throw ProtocolSourceException(
      'protocol.lock must use LF line endings; convert the file to LF',
    );
  }
  final lines = text.replaceFirst(RegExp(r'\n$'), '').split('\n');
  if (lines.length != 2) {
    throw ProtocolSourceException(
      'protocol.lock must have exactly two lines: the https address of '
      'idl.json and sha256:<64 lowercase hex digits>',
    );
  }
  final url = RegExp(r'\s').hasMatch(lines[0]) ? null : Uri.tryParse(lines[0]);
  if (url == null || !_isPlainHttps(url)) {
    throw ProtocolSourceException(
      'protocol.lock line 1 must be an https address without credentials '
      'or whitespace',
    );
  }
  final digest = _lockDigest.firstMatch(lines[1])?.group(1);
  if (digest == null) {
    throw ProtocolSourceException(
      'protocol.lock line 2 must be sha256:<64 lowercase hex digits>',
    );
  }
  return ProtocolLock(url: url, digest: digest);
}

void verifyIdlDigest(List<int> bytes, String expected) {
  final actual = sha256.convert(bytes).toString();
  if (actual != expected) {
    throw ProtocolSourceException(
      'The downloaded idl.json does not match protocol.lock: '
      'expected sha256 $expected, got $actual',
    );
  }
}

Future<List<int>> fetchLockedIdl(
  ProtocolLock lock, {
  IdlDownloader download = downloadIdl,
}) async {
  final bytes = await download(lock.url);
  verifyIdlDigest(bytes, lock.digest);
  return bytes;
}

// 逐跳处理重定向，不交给 HttpClient 自动跟随：自动跟随不检查每一跳是否仍为
// https。不设置任何请求头、凭据或 Cookie。
Future<List<int>> downloadIdl(
  Uri uri, {
  HttpClient Function() newClient = HttpClient.new,
  Duration timeout = _downloadTimeout,
}) async {
  _requireHttps(uri);
  final client = newClient()..connectionTimeout = _connectionTimeout;
  try {
    return await _fetch(client, uri).timeout(timeout);
  } on ProtocolSourceException {
    rethrow;
  } on TimeoutException {
    throw ProtocolSourceException('Downloading ${_describe(uri)} timed out');
  } on Object catch (error) {
    // 底层异常（如 HttpException）的文本含完整地址，包括签名查询串。
    throw ProtocolSourceException(
      'Could not download from ${uri.host}: ${error.runtimeType}',
    );
  } finally {
    client.close(force: true);
  }
}

Future<List<int>> _fetch(HttpClient client, Uri start) async {
  var current = start;
  for (var redirects = 0; redirects <= _maxRedirects; redirects++) {
    final request = await client.getUrl(current);
    request.followRedirects = false;
    final response = await request.close();
    final status = response.statusCode;
    if (const {301, 302, 303, 307, 308}.contains(status)) {
      final location = response.headers.value(HttpHeaders.locationHeader);
      if (location == null || location.isEmpty) {
        throw ProtocolSourceException(
          'Redirect from ${_describe(current)} has no Location header',
        );
      }
      current = current.resolve(location);
      _requireHttps(current);
      continue;
    }
    if (status != HttpStatus.ok) {
      throw ProtocolSourceException(
        'Downloading ${_describe(current)} failed with HTTP $status',
      );
    }
    return _readLimited(response, current);
  }
  throw ProtocolSourceException(
    'Downloading ${_describe(start)} was redirected more than '
    '$_maxRedirects times',
  );
}

Future<List<int>> _readLimited(HttpClientResponse response, Uri uri) async {
  final tooLarge = ProtocolSourceException(
    '${_describe(uri)} is larger than 1 MiB',
  );
  if (response.contentLength > _maxIdlBytes) throw tooLarge;
  final bytes = BytesBuilder(copy: false);
  await for (final chunk in response) {
    bytes.add(chunk);
    if (bytes.length > _maxIdlBytes) throw tooLarge;
  }
  return bytes.takeBytes();
}

Future<List<int>> readIdlSource(
  String? source, {
  required File lockFile,
  required void Function(String message) notice,
  IdlDownloader download = downloadIdl,
}) async {
  if (source == null) {
    if (!await lockFile.exists()) {
      throw ProtocolSourceException(
        'protocol.lock not found at ${lockFile.path}; '
        'pass --source to use a local idl.json',
      );
    }
    return fetchLockedIdl(
      parseProtocolLock(await lockFile.readAsString()),
      download: download,
    );
  }
  if (!source.contains('://')) return File(source).readAsBytes();
  final uri = Uri.tryParse(source);
  if (uri == null) {
    throw ProtocolSourceException('--source is not a valid address');
  }
  _requireHttps(uri);
  final bytes = await download(uri);
  notice(
    'Warning: ${_describe(uri)} was downloaded without sha256 verification '
    '(未校验); protocol.lock was not consulted',
  );
  return bytes;
}

Future<String> _formatDart(String source, String path) async {
  // --stdin-name 让格式化器使用生成物所属包的语言版本，结果才与在仓库上运行
  // `dart format` 一致。
  final process = await Process.start(Platform.resolvedExecutable, [
    'format',
    '--stdin-name',
    path,
  ]);
  final output = utf8.decoder.bind(process.stdout).join();
  final errors = utf8.decoder.bind(process.stderr).join();
  process.stdin.write(source);
  await process.stdin.close();
  if (await process.exitCode != 0) {
    throw FormatException('$path could not be formatted: ${await errors}');
  }
  return output;
}

Future<void> main(List<String> arguments) async {
  exitCode = await runGenerator(
    arguments,
    packageRoot: Platform.script.resolve('../'),
    out: stdout,
    err: stderr,
  );
}

/// 返回进程退出码；[packageRoot] 须以 `/` 结尾。
Future<int> runGenerator(
  List<String> arguments, {
  required Uri packageRoot,
  required StringSink out,
  required StringSink err,
  IdlDownloader download = downloadIdl,
}) async {
  try {
    String? sourcePath;
    var check = false;
    for (var index = 0; index < arguments.length; index++) {
      switch (arguments[index]) {
        case '--source':
          if (sourcePath != null || index + 1 >= arguments.length) {
            throw const FormatException(
              '--source requires one path or https address\n$_usage',
            );
          }
          sourcePath = arguments[++index];
        case '--check':
          check = true;
        default:
          throw FormatException(
            'Unknown argument: ${arguments[index]}\n$_usage',
          );
      }
    }
    final idl = jsonDecode(
      utf8.decode(
        await readIdlSource(
          sourcePath,
          lockFile: File.fromUri(packageRoot.resolve('protocol.lock')),
          notice: err.writeln,
          download: download,
        ),
      ),
    );
    if (idl is! Map<String, Object?>) {
      throw FormatException(
        '${sourcePath ?? 'protocol.lock'}: the IDL root must be an object',
      );
    }
    final generator = _Generator(idl);
    final directory = packageRoot.resolve('lib/core/protocol/');
    final outputs = <File, String>{};
    for (final (name, source) in [
      ('protocol.gen.dart', generator.protocol()),
      ('http.gen.dart', generator.http()),
    ]) {
      final file = File.fromUri(directory.resolve(name));
      outputs[file] = await _formatDart(source, file.path);
    }
    if (check) {
      final stale = <String>[];
      for (final MapEntry(key: file, value: expected) in outputs.entries) {
        if (!await file.exists() || await file.readAsString() != expected) {
          stale.add(file.path);
        }
      }
      if (stale.isNotEmpty) {
        throw FormatException(
          'Generated protocol files are stale: ${stale.join(', ')}',
        );
      }
      out.writeln('Protocol generation check passed.');
      return 0;
    }
    await Directory.fromUri(directory).create(recursive: true);
    for (final MapEntry(key: file, value: content) in outputs.entries) {
      await file.writeAsString(content);
    }
    out.writeln('Generated ${outputs.length} protocol files.');
    return 0;
  } on Object catch (error) {
    err.writeln(error);
    return 1;
  }
}
