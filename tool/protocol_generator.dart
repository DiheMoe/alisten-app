  }

  void _addClass(String name, Object? value, String where) {
    if (value == null) return;
    final schema = _object(value, where);
    final reference = schema[r'$ref'];
    if (reference != null) {
      _allowOnly(schema, const {r'$ref', 'description'}, where);
      _resolve(reference, where);
      return;
    }
    _declarations.add(_parseObject(name, schema, where));
  }

  _Class _parseObject(String name, _Json schema, String where) {
    _allowOnly(schema, const {
      'type',
      'description',
      'properties',
      'required',
      'additionalProperties',
      'oneOf',
      'allOf',
    }, where);
    if (schema['type'] != 'object') {
      throw FormatException('$where: expected an object schema');
    }
    _types.declare(name, where);
    final properties = _schemaMap(schema['properties'], '$where.properties');
    final required = _texts(schema['required'], '$where.required').toSet();
    for (final key in required) {
      if (!properties.containsKey(key)) {
        throw FormatException('$where.required: $key is not a property');
      }
    }
    final members = _Names('field', {
      ..._objectMembers,
      'fromJson': name,
      'toJson': name,
    });
    final fields = <_Field>[];
    for (final key in properties.keys.toList()..sort()) {
      final fieldWhere = '$where.properties.$key';
      final isRequired = required.contains(key);
      final (type, isNullable) = _parseField(
        properties[key]!,
        fieldWhere,
        isRequired: isRequired,
      );
      final fieldName = _identifier(_lowerCamel(key, fieldWhere));
      members.declare(fieldName, fieldWhere);
      fields.add(
        _Field(
          key,
          fieldName,
          type,
          isRequired: isRequired,
          isNullable: isNullable,
        ),
      );
    }
    final alternatives = [
      for (final (alternative, alternativeWhere) in _items(
        schema['oneOf'],
        '$where.oneOf',
      ))
        _parseAlternative(alternative, properties, alternativeWhere),
    ];
    // allOf 只收窄取值范围：回复按宽松规则解码，请求由服务端校验，因此不生成
    // allOf 规则。
    return _Class(name, fields, alternatives);
  }

  _Alternative _parseAlternative(
    _Json alternative,
    Map<String, _Json> outer,
    String where,
  ) {
    _allowOnly(alternative, const {
      'properties',
      'required',
      'additionalProperties',
    }, where);
    final properties = _schemaMap(
      alternative['properties'],
      '$where.properties',
    );
    for (final MapEntry(:key, :value) in properties.entries) {
      _allowOnly(value, const {}, '$where.properties.$key');
      if (!outer.containsKey(key)) {
        throw FormatException('$where.properties.$key: not an object property');
      }
    }
    final required = _texts(alternative['required'], '$where.required');
    if (required.isEmpty || !required.every(properties.containsKey)) {
      throw FormatException(
        '$where.required: must name some of the alternative properties',
      );
    }
    return _Alternative(required.toSet(), properties.keys.toSet());
  }

  (_Type, bool) _parseField(
    _Json schema,
    String where, {
    required bool isRequired,
  }) {
    if (schema.containsKey('anyOf')) {
      _allowOnly(schema, const {'anyOf', 'description'}, where);
      final alternatives = _items(schema['anyOf'], '$where.anyOf').toList();
      final nullType = alternatives.length == 2 ? alternatives[1].$1 : null;
      if (nullType == null ||
          nullType.length != 1 ||
          nullType['type'] != 'null') {
        throw FormatException(
          '$where: anyOf must be [schema, {"type": "null"}]',
        );
      }
      if (!isRequired) {
        throw FormatException('$where: nullable fields must be required');
      }
      return (_parseValue(alternatives[0].$1, '$where.anyOf[0]'), true);
    }
    if (schema['type'] == 'array') {
      _allowOnly(schema, const {
        'type',
        'description',
        'items',
        'minItems',
        'maxItems',
      }, where);
      final items = _object(schema['items'], '$where.items');
      return (_ListOf(_parseValue(items, '$where.items')), false);
    }
    return (_parseValue(schema, where), false);
  }

  _Type _parseValue(_Json schema, String where) {
    final reference = schema[r'$ref'];
    if (reference == null) return _scalar(schema, where, isDef: false);
    _allowOnly(schema, const {r'$ref', 'description'}, where);
    final name = _resolve(reference, where);
    final definition = _defs[name]!;
    if (definition['type'] == 'object') return _Named(name, isEnum: false);
    if (definition.containsKey('enum')) return _Named(name, isEnum: true);
    return _scalar(definition, '\$defs.$name', isDef: true);
  }

  _Scalar _scalar(_Json schema, String where, {required bool isDef}) {
    switch (schema['type']) {
      case 'string':
        _allowOnly(schema, {..._stringKeywords, if (isDef) 'x-url'}, where);
        return _string;
      case 'integer':
        _allowOnly(schema, _integerKeywords, where);
        return _integer;
      case 'number' when !isDef:
        _allowOnly(schema, const {'type', 'description'}, where);
        return _number;
      case 'boolean' when !isDef:
        _allowOnly(schema, const {'type', 'description'}, where);
        return _boolean;
      default:
        throw FormatException(
          '${_where(where)}: unsupported type ${jsonEncode(schema['type'])}',
        );
    }
  }

  _Enum _parseEnum(String name, _Json schema, String where) {
    _allowOnly(schema, const {
      'type',
      'description',
      'enum',
      'x-httpStatus',
    }, where);
    final wireValues = _texts(schema['enum'], '$where.enum');
    if (schema['type'] != 'string' || wireValues.isEmpty) {
      throw FormatException('$where: enums must be non-empty string enums');
    }
    _types.declare(name, where);
    final members = _Names('enum value', {
      ..._objectMembers,
      for (final member in const [
        'fromJson',
        'index',
        'name',
        'toJson',
        'values',
        'wireValue',
      ])
        member: name,
    });
    final values = <({String dart, String wire})>[];
    for (var index = 0; index < wireValues.length; index++) {
      final valueWhere = '$where.enum[$index]';
      final dart = _identifier(_lowerCamel(wireValues[index], valueWhere));
      members.declare(dart, valueWhere);
      values.add((dart: dart, wire: wireValues[index]));
    }
    return _Enum(name, values);
  }

  void _addEndpoint(String name, _Json binding, String auth, String where) {
    final constant = _identifier(_lowerCamel(name, where));
    _endpointNames.declare(constant, where);
    final status = binding['status'] ?? 200;
    final location = binding['location'] ?? false;
    if (status is! int || location is! bool) {
      throw FormatException(
        '$where: status must be an integer and location '
        'a boolean',
      );
    }
    _endpoints.add(
      _Endpoint(
        constant: constant,
        name: name,
        method: _text(binding['method'], '$where.method'),
        path: _text(binding['path'], '$where.path'),
        auth: auth,
        status: status,
        location: location,
      ),
    );
  }

  void _declareConstant(
    _Constants constants,
    String name,
    String literal,
    String where,
  ) {
    final identifier = _identifier(_lowerCamel(name, where));
    constants.names.declare(identifier, where);
    constants.values.add((name: identifier, literal: literal));
  }

  String _resolve(Object? reference, String where) {
    const prefix = r'#/$defs/';
    if (reference is String && reference.startsWith(prefix)) {
      final name = reference.substring(prefix.length);
      if (_defs.containsKey(name)) return name;
    }
    throw FormatException('${_where(where)}: unknown reference $reference');
  }

  String _renderEnum(_Enum model) {
    final name = model.name;
    final out = StringBuffer('enum $name {\n');
    for (var index = 0; index < model.values.length; index++) {
      final value = model.values[index];
      final terminator = index == model.values.length - 1 ? ';' : ',';
      out.writeln('  ${value.dart}(${_quote(value.wire)})$terminator');
    }
    return (out
          ..writeln()
          ..writeln('  const $name(this.wireValue);')
          ..writeln()
          ..writeln('  final String wireValue;')
          ..writeln()
          ..writeln(
            '  static $name fromJson(Object? value) => readEnum(value, '
            'values, (candidate) => candidate.wireValue, ${_quote(name)});',
          )
          ..writeln()
          ..writeln('  String toJson() => wireValue;')
          ..writeln('}'))
        .toString();
  }

  String _renderClass(_Class model) {
    final name = model.name;
    final out = StringBuffer('class $name {\n');
    if (model.fields.isEmpty) {
      return (out
            ..writeln('  const $name();')
            ..writeln()
            ..writeln(
              '  factory $name.fromJson(Map<String, Object?> json) => '
              'const $name();',
            )
            ..writeln()
            ..writeln('  Map<String, Object?> toJson() => <String, Object?>{};')
            ..writeln('}'))
          .toString();
    }
    out.writeln('  const $name({');
    for (final field in model.fields) {
      out.writeln(
        field.isRequired
            ? '    required this.${field.name},'
            : '    this.${field.name},',
      );
    }
    out.write('  })');
    if (model.alternatives.isNotEmpty) {
      out.write(
        ' : assert(${_alternativesCheck(model)}, '
        '${_quote('$name must match exactly one oneOf alternative')})',
      );
    }
    out
      ..writeln(';')
      ..writeln()
      ..writeln('  factory $name.fromJson(Map<String, Object?> json) {')
      ..writeln('    return $name(');
    for (final field in model.fields) {
      out.writeln('      ${field.name}: ${_decodeField(name, field)},');
    }
    out
      ..writeln('    );')
      ..writeln('  }')
      ..writeln();
    for (final field in model.fields) {
      final optional = field.isNullable || !field.isRequired ? '?' : '';
      out.writeln('  final ${_dartType(field.type)}$optional ${field.name};');
    }
    out
      ..writeln()
      ..writeln('  Map<String, Object?> toJson() => <String, Object?>{');
    for (final field in model.fields) {
      out.writeln('    ${_quote(field.key)}: ${_encodeField(field)},');
    }
    return (out
          ..writeln('  };')
          ..writeln('}'))
        .toString();
  }

  // 请求须恰好匹配 oneOf 的一个分支：该分支的必填字段都已设置，分支外的字段
  // 都未设置。
  String _alternativesCheck(_Class model) {
    final branches = model.alternatives.map((alternative) {
      final conditions = [
        for (final field in model.fields)
          if (alternative.required.contains(field.key))
            '${field.name} != null'
          else if (!alternative.properties.contains(field.key))
            '${field.name} == null',
      ];
      return '(${conditions.join(' && ')} ? 1 : 0)';
    });
    return '${branches.join(' + ')} == 1';
  }

  String _decodeField(String owner, _Field field) {
    final reader = field.isRequired ? 'requiredField' : 'optionalField';
    final source = '$reader(json, ${_quote(field.key)}, ${_quote(owner)})';
    final path = '$owner.${field.key}';
    if (field.isRequired && !field.isNullable) {
      return _decode(field.type, source, path);
    }
    return 'switch ($source) { null => null, '
        'final value => ${_decode(field.type, 'value', path)}, }';
  }

  String _decode(_Type type, String source, String path) {
    return switch (type) {
      _Scalar(:final reader) => '$reader($source, ${_quote(path)})',
      _Named(:final name, isEnum: true) => '$name.fromJson($source)',
      _Named(:final name) =>
        '$name.fromJson(readObject($source, ${_quote(path)}))',
      _ListOf(:final item) =>
        'readList($source, ${_quote(path)}).map((item) => '
            '${_decode(item, 'item', '$path[]')}).toList(growable: false)',
    };
  }

  String _encodeField(_Field field) {
    final isOptional = !field.isRequired;
    final value = _encode(
      field.type,
      field.name,
      nullable: field.isNullable || isOptional,
    );
    return isOptional ? '?$value' : value;
  }

  String _encode(_Type type, String source, {required bool nullable}) {
    final access = nullable ? '?.' : '.';
    return switch (type) {
      _Scalar() || _ListOf(item: _Scalar()) => source,
      _Named() => '$source${access}toJson()',
      _ListOf() =>
        '$source${access}map((item) => item.toJson())'
            '.toList(growable: false)',
    };
  }

  String _dartType(_Type type) {
    return switch (type) {
      _Scalar(:final dart) => dart,
      _Named(:final name) => name,
      _ListOf(:final item) => 'List<${_dartType(item)}>',
    };
  }

  String _renderConstants(String name, _Constants constants, String? type) {
    final out = StringBuffer('abstract final class $name {\n');
    for (final constant in constants.values) {
      out.writeln('  static const ${constant.name} = ${constant.literal};');
    }
    if (type != null) {
      final names = constants.values.map((constant) => constant.name);
      out.writeln('  static const values = <$type>[${names.join(', ')}];');
    }
    return (out..writeln('}')).toString();
  }
}

final class _Constants {
  final names = _Names('constant', {
    ..._objectMembers,
    'values': 'the generated values list',
  });
  final values = <({String name, String literal})>[];
}

Never _missing(String where) => throw FormatException('$where: missing');

void _allowOnly(_Json node, Set<String> allowed, String where) {
  for (final key in node.keys) {
    if (!allowed.contains(key)) {
      throw FormatException('${_where(where)}: unsupported keyword "$key"');
    }
  }
}

String _at(String where, String key) => where.isEmpty ? key : '$where.$key';

String _where(String where) => where.isEmpty ? 'top level' : where;

_Json _object(Object? value, String where) {
  if (value is Map<String, Object?>) return value;
  throw FormatException('${_where(where)}: must be an object');
}

Map<String, _Json> _schemaMap(Object? value, String where) {
  if (value == null) return const {};
  return {
    for (final MapEntry(:key, :value) in _object(value, where).entries)
      key: _object(value, '$where.$key'),
  };
}

Iterable<(_Json, String)> _items(Object? value, String where) {
  if (value == null) return const [];
  if (value is! List<Object?>) {
    throw FormatException('$where: must be an array');
  }
  return [
    for (var index = 0; index < value.length; index++)
      (_object(value[index], '$where[$index]'), '$where[$index]'),
  ];
}

String _text(Object? value, String where) {
  if (value is String) return value;
  throw FormatException('$where: must be a string');
}

List<String> _texts(Object? value, String where) {
  if (value == null) return const [];
  if (value is List<Object?> && value.every((item) => item is String)) {
    return value.cast<String>();
  }
  throw FormatException('$where: must be an array of strings');
}

