    final type = _text(operation['type'], '$where.type');
    final name = _pascal(type, '$where.type');
    _addClass(
      '${name}Request',
      operation['request'] ?? _missing('$where.request'),
      '$where.request',
    );
    _addClass(
      '${name}Response',
      operation['response'] ?? _missing('$where.response'),
      '$where.response',
    );
    return type;
