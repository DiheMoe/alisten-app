  Set<String> _reachableDefs() {
    final reachable = <String>{};

    void visit(Object? value) {
      if (value is Map<String, Object?>) {
        final reference = value[r'$ref'];
        if (reference is String && reference.startsWith(r'#/$defs/')) {
          final name = reference.substring(r'#/$defs/'.length);
          final schema = _defs[name];
          if (schema != null && reachable.add(name)) {
            visit(schema);
          }
        }
        for (final entry in value.entries) {
          if (entry.key != r'$ref') visit(entry.value);
        }
      } else if (value is List<Object?>) {
        value.forEach(visit);
      }
    }

    final ws = _idl['x-ws'];
    if (ws is Map<String, Object?>) {
      visit(ws['requests']);
      visit(ws['events']);
    }
    visit(_idl['x-requests']);
    visit(_idl['x-events']);
    visit(_idl['x-http']);
    return reachable;
  }

  void _parseDef(String name) {
    final schema = _defs[name]!;
    final where = '\$defs.$name';
    if (schema['type'] == 'object') {
      _declarations.add(_parseObject(name, schema, where));
    } else if (schema.containsKey('enum')) {
      _declarations.add(_parseEnum(name, schema, where));
    } else {
      _scalar(schema, where, isDef: true);
    }
  }

